def build() -> list[dict]:
    out = []
    for n, (cat, visual, title, score, sents, kws) in enumerate(SEED, 1):
        out.append({
            "id": f"fa-seed-{n:04d}",
            "category": cat,
            "visual": visual,
            "title": title,
            "sentences": sents,
            "keywords": kws,
            "virality_score": score,
            "verified": True,
            "source": "curated",
            "status": "available",
        })
    return out


if __name__ == "__main__":
    force = "--force" in sys.argv
    if bank.BANK.exists() and not force:
        print(json.dumps({"skipped": "bank exists (use --force to overwrite; this would drop expanded ideas)"}))
        raise SystemExit(0)
    ideas = build()
    idx = bank.DedupIndex()
    bad = 0
    for i in ideas:
        errs = bank.validate(i)
        dup = idx.is_duplicate(i)
        if errs or dup:
            bad += 1
            print("PROBLEM", i["id"], errs, "dup" if dup else "")
        idx.add(i)
    out = bank.BANK
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        for i in ideas:
            f.write(json.dumps(i, ensure_ascii=False) + "\n")
    print(json.dumps({"written": len(ideas), "problems": bad, "path": str(out)}, ensure_ascii=False))
